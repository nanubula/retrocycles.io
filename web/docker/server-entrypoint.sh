#!/bin/bash
# Entry point of the aa-server-styctap image. /data is the mounted state directory:
# /data/var/autoexec.cfg is the admin's configuration (created on first start),
# /data/config/docker.cfg is rewritten from the environment on every start:
#   WEBRTC_ENABLE (1), WEBRTC_SIGNAL_PORT (4535), WEBRTC_SIGNAL_BIND (0.0.0.0),
#   WEBRTC_PORT_MIN (50000), WEBRTC_PORT_MAX (50100), WEBRTC_PUBLIC_IP (unset),
#   WEBRTC_TRUSTED_PROXIES (unset: the server's default, loopback only),
#   SERVER_PORT (4534), SERVER_NAME, TALK_TO_MASTER (1).
# Extra arguments go to armagetronad-dedicated.
set -e

DATA=/data
VAR="$DATA/var"
CONFIG="$DATA/config"
mkdir -p "$VAR" "$CONFIG" "$DATA/resource"

{
    echo "# generated by server-entrypoint.sh from the container environment; edit autoexec.cfg instead"
    echo "SERVER_PORT ${SERVER_PORT:-4534}"
    echo "TALK_TO_MASTER ${TALK_TO_MASTER:-1}"
    [ -n "${SERVER_NAME:-}" ] && echo "SERVER_NAME ${SERVER_NAME}"
    echo "WEBRTC_ENABLE ${WEBRTC_ENABLE:-1}"
    echo "WEBRTC_SIGNAL_PORT ${WEBRTC_SIGNAL_PORT:-4535}"
    echo "WEBRTC_SIGNAL_BIND ${WEBRTC_SIGNAL_BIND:-0.0.0.0}"
    echo "WEBRTC_PORT_MIN ${WEBRTC_PORT_MIN:-50000}"
    echo "WEBRTC_PORT_MAX ${WEBRTC_PORT_MAX:-50100}"
    [ -n "${WEBRTC_PUBLIC_IP:-}" ] && echo "WEBRTC_PUBLIC_IP ${WEBRTC_PUBLIC_IP}"
    [ -n "${WEBRTC_TRUSTED_PROXIES:-}" ] && echo "WEBRTC_TRUSTED_PROXIES ${WEBRTC_TRUSTED_PROXIES}"
    true
} > "$CONFIG/docker.cfg"

if [ ! -e "$VAR/autoexec.cfg" ]; then
    cat > "$VAR/autoexec.cfg" <<'EOF'
# Your settings. docker.cfg (generated from the environment) is read first; anything
# here overrides it.
EOF
fi

if [ "$(id -u)" = 0 ]; then
    chown -R nobody:nogroup "$DATA"
    EXEC="setpriv --reuid=nobody --regid=nogroup --clear-groups"
else
    EXEC=""
fi

# --extraconfig takes a name relative to the config directories; /data/config is one
# of them through --userdatadir. Load order: settings*.cfg, docker.cfg, autoexec.cfg.
exec $EXEC /opt/armagetronad/bin/armagetronad-dedicated \
    --userdatadir "$DATA" \
    --vardir "$VAR" \
    --autoresourcedir "$DATA/resource" \
    --extraconfig docker.cfg \
    --daemon "$@"
